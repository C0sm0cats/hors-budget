// Regenerate the committed PNGs and their self-contained runtime data: node scripts/generate-office-plaques.cjs
const {chromium}=require('@playwright/test');
const {writeFileSync,readFileSync}=require('node:fs');
const {execFileSync}=require('node:child_process');
const {resolve}=require('node:path');
const root=resolve(__dirname,'..');
const people={
  projectDirector:{name:'DIRECTION PROJETS',role:['DIRECTEUR DE PROJETS']},
  businessManager:{name:'DÉVELOPPEMENT COMMERCIAL',role:['BUSINESS MANAGER']},
  techServicesDirector:{name:'TECHNOLOGIES & SERVICES',role:['DIRECTEUR TECHNOLOGIES SERVICES','PAYS DE LA LOIRE']},
  regionalDirector:{name:'DIRECTION RÉGIONALE',role:['DIRECTEUR RÉGION','GRAND OUEST']}
};
(async()=>{
  const browser=await chromium.launch();
  try{
    const page=await browser.newPage();
    const assets=await page.evaluate(people=>{
      const output={};
      for(const [key,person] of Object.entries(people)){
        const canvas=document.createElement('canvas'),c=canvas.getContext('2d');
        const fonts=['700 36px Arial',...person.role.map(()=> '700 18px Arial')];
        const lines=[person.name,...person.role];
        // Measure the visible glyphs, including accents; never squeeze text with maxWidth.
        const metrics=lines.map((text,i)=>{c.font=fonts[i];const m=c.measureText(text);return {left:m.actualBoundingBoxLeft,right:m.actualBoundingBoxRight,ascent:m.actualBoundingBoxAscent,descent:m.actualBoundingBoxDescent};});
        const padding=22,gaps=lines.map((_,i)=>i===0?0:i===1?13:8);
        const width=Math.ceil(Math.max(...metrics.map(m=>m.left+m.right))+padding*2);
        const height=Math.ceil(metrics.reduce((sum,m,i)=>sum+m.ascent+m.descent+gaps[i],padding*2));
        // 2x export keeps the in-game texture crisp without oversized source images.
        canvas.width=width*2;canvas.height=height*2;c.scale(2,2);
        const metal=c.createLinearGradient(0,0,width,height);
        for(const [at,color] of [[0,'#f2e6c5'],[.24,'#bca16d'],[.48,'#eee0bb'],[.76,'#a28552'],[1,'#dbc599']])metal.addColorStop(at,color);
        c.fillStyle=metal;c.fillRect(0,0,width,height);
        c.strokeStyle='#6e5b3f';c.lineWidth=1;c.strokeRect(.5,.5,width-1,height-1);
        const enamel=c.createLinearGradient(0,0,0,height);enamel.addColorStop(0,'#263b46');enamel.addColorStop(1,'#101f29');
        c.fillStyle=enamel;c.fillRect(5,5,width-10,height-10);
        c.strokeStyle='#e3d0a0';c.lineWidth=.6;c.strokeRect(7.5,7.5,width-15,height-15);
        // A subtle top reflection gives the inset a physical edge without reducing contrast.
        c.fillStyle='#ffffff0b';c.fillRect(9,9,width-18,2);
        let y=padding;
        lines.forEach((text,i)=>{
          const m=metrics[i];y+=gaps[i]+m.ascent;
          c.font=fonts[i];c.textBaseline='alphabetic';c.fillStyle=i===0?'#f6e7be':'#ecf0eb';
          const x=(width-m.left-m.right)/2+m.left;
          c.fillText(text,x,y);y+=m.descent;
        });
        output[key]={...person,width:canvas.width,height:canvas.height,padding:padding*2,png:canvas.toDataURL('image/png')};
      }
      return output;
    },people);
    for(const [key,asset] of Object.entries(assets)){
      const path=resolve(root,'plaques',key+'.png');
      writeFileSync(path,Buffer.from(asset.png.split(',')[1],'base64'));
      // Requires Pillow at build time only; a compact palette preserves crisp lettering.
      execFileSync('python3',['-c',"from PIL import Image; import sys; p=sys.argv[1]; im=Image.open(p).convert('RGB'); im.quantize(colors=128,dither=Image.Dither.NONE).save(p,optimize=True)",path]);
      asset.png='data:image/png;base64,'+readFileSync(path).toString('base64');
    }
    writeFileSync(resolve(root,'office-plaques-data.js'),"'use strict';\n// Generated by scripts/generate-office-plaques.cjs. PNG data also supports file:// without tainting WebGL.\nglobalThis.OfficePlaqueAssets="+JSON.stringify(assets)+';\n');
    console.log(Object.entries(assets).map(([key,a])=>`${key}: ${a.width}×${a.height}, ${Buffer.from(a.png.split(',')[1],'base64').length} bytes`).join('\n'));
  }finally{await browser.close();}
})();
